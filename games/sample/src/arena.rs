//! The arena: a floor, a ring of pillars and a cluster of spinning cubes (the M1 test scene,
//! kept as decoration).

use ge_engine::prelude::*;

/// Half-size of the walkable floor.
pub const ARENA_HALF_SIZE: f32 = 15.0;

ge_core::declare_cvar!(pub static SAMPLE_STRESS_LIGHTS: u32 = (
    "sample.StressLights",
    0,
    "Extra small point lights scattered over the arena at startup (M4 performance gate: 256)"
));

/// Rotates the entity around a local axis at a constant rate (visual only).
#[derive(Component, Copy, Clone, Debug)]
pub struct Spin {
    pub axis: Vec3,
    /// Radians per second.
    pub speed: f32,
}

pub fn spawn_arena(mut commands: Commands, assets: Option<ResMut<AssetServer>>) {
    // A glTF prop from assets/ (generated by `cargo xtask gen-assets`): loads in the
    // background and appears when ready; edits to the file show up live.
    if let Some(mut assets) = assets {
        commands.spawn((
            Name::new("Crate"),
            Transform::from_xyz(4.0, 0.0, -3.0)
                .with_rotation(Quat::from_rotation_y(0.4))
                .with_scale(Vec3::splat(1.4)),
            SceneRoot(assets.load("models/crate.glb")),
        ));
    }

    commands.spawn((
        Name::new("Floor"),
        Transform::default().with_scale(Vec3::splat(ARENA_HALF_SIZE)),
        MeshRenderer::new(MeshKind::Plane, [0.55, 0.55, 0.58]),
    ));

    // The sun used in Rendered shading (Solid shading keeps the fixed studio light, so the
    // game's look is unchanged). Same direction as the studio light.
    commands.spawn((
        Name::new("Sun"),
        Transform::from_xyz(7.0, 20.0, 9.0).looking_at(Vec3::ZERO, Vec3::Y),
        Light {
            power: 2.0,
            ..Light::new(LightKind::Sun)
        },
    ));

    // Shadowed local lights (plan 0006): a warm spot on the crate, a cool spot on the cube
    // cluster and a point light in the middle of the arena.
    commands.spawn((
        Name::new("Spot.Crate"),
        Transform::from_xyz(8.0, 6.0, -0.5).looking_at(Vec3::new(4.0, 0.0, -3.0), Vec3::Y),
        Light {
            power: 1500.0,
            color: Vec3::new(1.0, 0.78, 0.55),
            spot_size: 50f32.to_radians(),
            spot_blend: 0.3,
            radius: 0.2,
            ..Light::new(LightKind::Spot)
        },
    ));
    commands.spawn((
        Name::new("Spot.Cluster"),
        Transform::from_xyz(-3.0, 7.0, -3.0).looking_at(Vec3::new(-7.0, 0.0, -7.0), Vec3::Y),
        Light {
            power: 2000.0,
            color: Vec3::new(0.55, 0.7, 1.0),
            spot_size: 55f32.to_radians(),
            spot_blend: 0.25,
            radius: 0.2,
            ..Light::new(LightKind::Spot)
        },
    ));
    commands.spawn((
        Name::new("Point.Center"),
        Transform::from_xyz(0.0, 3.0, 4.0),
        Light {
            power: 600.0,
            color: Vec3::new(1.0, 0.9, 0.8),
            radius: 0.15,
            ..Light::new(LightKind::Point)
        },
    ));

    // `-cvar sample.StressLights=N`: unshadowed lights on a golden-angle spiral, for
    // measuring clustered shading.
    let stress = SAMPLE_STRESS_LIGHTS.get();
    for i in 0..stress {
        let t = (i as f32 + 0.5) / stress as f32;
        let r = t.sqrt() * (ARENA_HALF_SIZE - 1.0);
        let a = i as f32 * 2.399_963;
        commands.spawn((
            Name::new(format!("Stress.{:03}", i + 1)),
            Transform::from_xyz(a.cos() * r, 0.6 + (i % 4) as f32 * 0.4, a.sin() * r),
            Light {
                power: 40.0,
                color: Vec3::from(palette(i as f32 * 0.137 % 1.0)),
                cast_shadow: false,
                use_custom_distance: true,
                custom_distance: 3.0,
                ..Light::new(LightKind::Point)
            },
        ));
    }

    let pillars = 10;
    for i in 0..pillars {
        let angle = i as f32 / pillars as f32 * std::f32::consts::TAU;
        let radius = ARENA_HALF_SIZE - 2.0;
        commands.spawn((
            Name::new(format!("Pillar.{:03}", i + 1)),
            Transform::from_xyz(angle.cos() * radius, 2.0, angle.sin() * radius)
                .with_scale(Vec3::new(1.2, 4.0, 1.2)),
            MeshRenderer::new(MeshKind::Cube, [0.35, 0.38, 0.45]),
        ));
    }

    // Floating cluster: one parent that spins, children that spin on their own axes.
    commands
        .spawn((
            Name::new("Cluster"),
            Transform::from_xyz(-7.0, 2.5, -7.0),
            Spin {
                axis: Vec3::Y,
                speed: 0.4,
            },
        ))
        .with_children(|cluster| {
            for i in 0..6 {
                let a = i as f32 / 6.0 * std::f32::consts::TAU;
                let hue = i as f32 / 6.0;
                cluster.spawn((
                    Name::new(format!("Cluster Cube.{:03}", i + 1)),
                    Transform::from_xyz(a.cos() * 2.0, (a * 2.0).sin() * 0.5, a.sin() * 2.0)
                        .with_scale(Vec3::splat(0.6)),
                    MeshRenderer::new(MeshKind::Cube, palette(hue)),
                    Spin {
                        axis: Vec3::new(1.0, 1.0, 0.0).normalize(),
                        speed: 1.5,
                    },
                ));
            }
        });
}

pub fn spin(time: Res<Time>, mut spinners: Query<(&Spin, &mut Transform)>) {
    let dt = time.delta_secs();
    for (spin, mut transform) in &mut spinners {
        transform.rotation =
            (transform.rotation * Quat::from_axis_angle(spin.axis, spin.speed * dt)).normalize();
    }
}

/// Cheap rainbow (cosine palette), linear RGB.
fn palette(t: f32) -> [f32; 3] {
    let tau = std::f32::consts::TAU;
    [
        0.5 + 0.45 * (tau * t).cos(),
        0.5 + 0.45 * (tau * (t + 0.33)).cos(),
        0.5 + 0.45 * (tau * (t + 0.67)).cos(),
    ]
}
